#!/usr/bin/env node
// Builds plugin/: a self-contained Claude Code plugin that needs only Node 22+ on a developer's
// machine. It holds the bundled CLI, the viewer, the schema, the skills, the hooks and the MCP
// server definition. The repo root's .claude-plugin/marketplace.json points at it.
//
//   npm run build:plugin
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'plugin');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, stdio: 'inherit' });

fs.rmSync(out, { recursive: true, force: true });

// 1. The CLI with every dependency inlined, and the single-file viewer.
run('npx', ['vite', 'build', '--config', 'scripts/vite.cli.config.ts']);
run('npx', ['vite', 'build', '--config', 'viewer/vite.config.ts', '--logLevel', 'warn']);

const copy = (from, to = from) => {
  const dst = path.join(out, to);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.cpSync(path.join(root, from), dst, { recursive: true });
};
copy('viewer/dist/index.html');
copy('schemas/armature.schema.json');
copy('skills');

// Launchers. The plugin's bin/ is on the PATH of Claude's Bash tool, so agents can run "armature show x".
// The launcher starts with the same model check as bin/armature.mjs: taken from that file, up to where it finds the CLI.
const devLauncher = fs.readFileSync(path.join(root, 'bin', 'armature.mjs'), 'utf8');
const head = devLauncher.slice(devLauncher.indexOf('import { existsSync }'), devLauncher.indexOf('const built ='));
const launcher = `${head}const cli = new URL('../dist/cli.mjs', import.meta.url);\nif (!existsSync(cli)) {\n  console.error('The armature plugin is incomplete: dist/cli.mjs is missing. Reinstall the plugin.');\n  process.exit(1);\n}\nawait import(cli.href);\n`;
fs.mkdirSync(path.join(out, 'bin'), { recursive: true });
fs.writeFileSync(path.join(out, 'bin', 'armature.mjs'), `#!/usr/bin/env node\n${launcher}`);
// A shell wrapper, so it works whatever package.json sits above the plugin folder.
fs.writeFileSync(path.join(out, 'bin', 'armature'), '#!/bin/sh\nexec node "$(dirname "$0")/armature.mjs" "$@"\n');
fs.chmodSync(path.join(out, 'bin', 'armature'), 0o755);
fs.chmodSync(path.join(out, 'bin', 'armature.mjs'), 0o755);

// 2. tree-sitter is loaded from disk at run time; vendor only the runtime and the grammars we parse.
const ts = 'node_modules/@vscode/tree-sitter-wasm';
for (const f of ['package.json', 'LICENSE', 'wasm/tree-sitter.js', 'wasm/tree-sitter.wasm', ...['typescript', 'tsx', 'javascript', 'python'].map((l) => `wasm/tree-sitter-${l}.wasm`)]) {
  copy(`${ts}/${f}`, `node_modules/@vscode/tree-sitter-wasm/${f}`);
}

// 3. Plugin manifest, hooks and MCP server. Paths go through ${CLAUDE_PLUGIN_ROOT}, never this machine.
const write = (rel, body) => {
  const p = path.join(out, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, typeof body === 'string' ? body : `${JSON.stringify(body, null, 2)}\n`);
};
const bin = '"${CLAUDE_PLUGIN_ROOT}/bin/armature.mjs"';
const hook = (name) => [{ type: 'command', command: `node ${bin} hook ${name}` }];
// The tools that write files: Claude Code's own, and the usual MCP file servers. Keep in step with WRITE_TOOLS in src/agent.ts.
const WRITE_TOOLS = 'Edit|Write|MultiEdit|NotebookEdit|mcp__.*__(write_file|edit_file|create_file|move_file|write_text_file)';
write('.claude-plugin/plugin.json', {
  name: 'armature',
  version: pkg.version,
  description: 'Architecture model in armature/: orientation at session start, context for the first prompt, planning through the model, model and document checks after edits, path-scoped rules, and an MCP server for the code graph.',
  author: { name: 'armature' },
  keywords: ['architecture', 'code-graph', 'documentation'],
});
write('hooks/hooks.json', {
  hooks: {
    SessionStart: [{ hooks: hook('session-start') }],
    UserPromptSubmit: [{ hooks: hook('prompt') }],
    PreToolUse: [
      { matcher: WRITE_TOOLS, hooks: hook('pre-write') },
      { matcher: 'Bash', hooks: hook('pre-bash') },
      { matcher: 'ExitPlanMode', hooks: hook('pre-plan') },
    ],
    PostToolUse: [{ matcher: WRITE_TOOLS, hooks: hook('post-edit') }],
    Stop: [{ hooks: hook('stop') }],
  },
});
write('.mcp.json', { mcpServers: { armature: { command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/bin/armature.mjs', 'mcp'] } } });
write(
  'README.md',
  `# armature plugin ${pkg.version}\n\nGenerated by \`npm run build:plugin\` in armature. Do not edit by hand.\n\nNeeds Node 22 or newer. Repos without an \`armature/\` folder are left alone: every hook exits silently.\n`,
);

const size = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? size(path.join(dir, e.name)) : fs.statSync(path.join(dir, e.name)).size), 0);
console.log(`plugin/ built: armature ${pkg.version}, ${(size(out) / 1e6).toFixed(1)} MB`);
