import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { ciWorkflow, install, installTeam, parseMarketplace, syncRules } from '../src/agent.js';

function repo(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'armature-team-'));
  const write = (rel: string, body: string): void => {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), body);
  };
  write('armature/system.yaml', 'name: Demo\npurpose: test\n');
  write('armature/nodes/api.yaml', 'id: api\nkind: service\nrole: serves the API\ncode: ["src/api/**"]\n');
  write('src/api/index.ts', 'export const x = 1;\n');
  return root;
}

describe('team install', () => {
  it('reads marketplace sources', () => {
    expect(parseMarketplace('acme/armature')).toEqual({ source: 'github', repo: 'acme/armature' });
    expect(parseMarketplace('https://github.com/acme/armature.git', 'v1')).toEqual({ source: 'github', repo: 'acme/armature', ref: 'v1' });
    expect(parseMarketplace('https://git.example.com/tools/armature.git')).toEqual({ source: 'git', url: 'https://git.example.com/tools/armature.git' });
    expect(parseMarketplace(path.resolve(__dirname, '..'))).toEqual({ source: 'directory', path: path.resolve(__dirname, '..') });
  });

  it('writes only shareable files and removes the local wiring', () => {
    const root = repo();
    install(root);
    const local = path.join(root, '.claude', 'settings.local.json');
    expect(fs.readFileSync(local, 'utf8')).toContain('armature.mjs');
    // Every hook is wired, including both on PreToolUse, and a second install changes nothing.
    const all = ['hook post-edit', 'hook pre-plan', 'hook pre-write', 'hook prompt', 'hook session-start', 'hook stop'];
    const hooksOf = (): string[] => (fs.readFileSync(local, 'utf8').match(/hook [a-z-]+/g) ?? []).sort();
    expect(hooksOf()).toEqual(all);
    install(root);
    expect(hooksOf()).toEqual(all);
    expect(fs.existsSync(path.join(root, '.claude', 'skills', 'armature-language'))).toBe(true);

    const out = installTeam(root, { marketplace: 'acme/armature' });
    const settings = JSON.parse(fs.readFileSync(path.join(root, '.claude', 'settings.json'), 'utf8'));
    expect(settings.enabledPlugins['armature@armature']).toBe(true);
    expect(settings.extraKnownMarketplaces['armature'].source).toEqual({ source: 'github', repo: 'acme/armature' });
    expect(fs.readFileSync(local, 'utf8')).not.toContain('armature.mjs');
    expect(fs.existsSync(path.join(root, '.mcp.json'))).toBe(false);
    expect(fs.existsSync(path.join(root, '.claude', 'skills'))).toBe(false);
    expect(fs.existsSync(path.join(root, '.claude', 'rules', 'armature-api.md'))).toBe(true);
    expect(out.join('\n')).toContain('architecture.yml');

    // Nothing committed names a path on this machine.
    for (const f of ['.claude/settings.json', '.github/workflows/architecture.yml', '.claude/rules/armature-api.md']) {
      expect(fs.readFileSync(path.join(root, f), 'utf8')).not.toContain(os.homedir());
    }
  });

  it('flags rule files that no longer match the model', () => {
    const root = repo();
    syncRules(root);
    expect(syncRules(root, { dryRun: true }).stale).toEqual([]);
    fs.writeFileSync(path.join(root, 'armature/nodes/api.yaml'), 'id: api\nkind: service\nrole: serves the public API\ncode: ["src/api/**"]\n');
    expect(syncRules(root, { dryRun: true }).stale).toEqual(['.claude/rules/armature-api.md']);
  });

  it('replaces what an install under the earlier name left behind', () => {
    const root = repo();
    const write = (rel: string, body: string): void => {
      fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
      fs.writeFileSync(path.join(root, rel), body);
    };
    write('.claude/settings.json', JSON.stringify({ enabledPlugins: { 'brain@agent-brain': true, 'other@market': true }, extraKnownMarketplaces: { 'agent-brain': { source: { source: 'github', repo: 'acme/agent-brain' } } } }));
    write('.claude/settings.local.json', JSON.stringify({ hooks: { Stop: [{ hooks: [{ type: 'command', command: 'node "/old/bin/brain.mjs" hook stop' }] }] } }));
    write('.mcp.json', JSON.stringify({ mcpServers: { brain: { type: 'stdio', command: 'node', args: ['/old/bin/brain.mjs', 'mcp'] } } }));
    write('.claude/rules/arch-api.md', '<!-- Generated by "brain sync-rules" from arch/nodes/api.yaml. Edit the model, not this file. -->\n');
    write('.claude/rules/arch-notes.md', 'Written by hand; not ours to remove.\n');
    write('.claude/skills/arch-design/SKILL.md', '---\nname: arch-design\n---\n');

    const out = installTeam(root, { marketplace: 'acme/armature' }).join('\n');
    const settings = JSON.parse(fs.readFileSync(path.join(root, '.claude', 'settings.json'), 'utf8'));
    expect(settings.enabledPlugins).toEqual({ 'other@market': true, 'armature@armature': true });
    expect(Object.keys(settings.extraKnownMarketplaces)).toEqual(['armature']);
    expect(fs.readFileSync(path.join(root, '.claude', 'settings.local.json'), 'utf8')).not.toContain('brain.mjs');
    expect(fs.existsSync(path.join(root, '.mcp.json'))).toBe(false);
    expect(fs.existsSync(path.join(root, '.claude/rules/arch-api.md'))).toBe(false);
    expect(fs.existsSync(path.join(root, '.claude/rules/armature-api.md'))).toBe(true);
    expect(fs.existsSync(path.join(root, '.claude/rules/arch-notes.md'))).toBe(true);
    // Copied skills may have been edited, so they are named, not deleted.
    expect(fs.existsSync(path.join(root, '.claude/skills/arch-design/SKILL.md'))).toBe(true);
    expect(out).toContain('replacing brain@agent-brain');
    expect(out).toContain('Old skills remain in .claude/skills/ (arch-design)');
  });

  it('leaves a committed .mcp.json alone', () => {
    const root = repo();
    const shared = `${JSON.stringify({ mcpServers: { team: { type: 'http', url: 'https://example.com/mcp' } } }, null, 2)}\n`;
    fs.writeFileSync(path.join(root, '.mcp.json'), shared);
    execFileSync('git', ['init', '-q'], { cwd: root });
    execFileSync('git', ['add', '.mcp.json'], { cwd: root });
    const out = install(root).join('\n');
    expect(fs.readFileSync(path.join(root, '.mcp.json'), 'utf8')).toBe(shared);
    expect(out).toContain('Skipped .mcp.json: it is committed');
  });

  it('builds a CI workflow for remote marketplaces only', () => {
    expect(ciWorkflow({ source: 'github', repo: 'acme/armature' })).toContain('repository: acme/armature');
    expect(ciWorkflow({ source: 'git', url: 'https://x/y.git', ref: 'v1' })).toContain('git clone --depth 1 --branch v1 https://x/y.git .armature');
    expect(ciWorkflow({ source: 'directory', path: '/x' })).toBeNull();
  });
});
