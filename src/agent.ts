function readStdin(): Promise<string> {
  // The launcher has already read the input, to decide whether this repo has a model at all.
  const given = (globalThis as { __ARMATURE_STDIN__?: unknown }).__ARMATURE_STDIN__;
  if (typeof given === 'string') return Promise.resolve(given);
  return new Promise((resolve) => {
    if (process.stdin.isTTY) return resolve('');
    let data = '';
    // A hook that is given no input must not hang. The timer is cleared once the input ends:
    // left running, it kept every hook alive for its full length.
    const giveUp = setTimeout(() => resolve(data), 1500);
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (c) => (data += c));
    process.stdin.on('end', () => {
      clearTimeout(giveUp);
      resolve(data);
    });
  });
}

/** The tools that write files: Claude Code's own, and the usual MCP file servers. */
export const WRITE_TOOLS = 'Edit|Write|MultiEdit|NotebookEdit|mcp__.*__(write_file|edit_file|create_file|move_file|write_text_file)';

function parseJson(text: string): any {
  try {
    return JSON.parse(text);
  } catch {
    return {};
  }
}

/** Writes one path-scoped rule file per node that owns code. Returns counts. With `dryRun`, only counts. */
export function syncRules(root: string, opts: { dryRun?: boolean } = {}): { written: number; removed: number; stale: string[] } {
  const g = compile(root);
  const dir = path.join(root, '.claude', 'rules');
  const stale: string[] = [];
  if (!opts.dryRun) fs.mkdirSync(dir, { recursive: true });
  const wanted = new Map<string, string>();
  for (const n of g.nodes) {
    if (n.code.length === 0) continue;
    const globs = n.code.filter((c) => !c.startsWith('!'));
    const lines: string[] = [];
    lines.push('---');
    lines.push('paths:');
    for (const c of globs) lines.push(`  - "${c}"`);
    lines.push('---');
    lines.push('');
    lines.push(`<!-- Generated by "armature sync-rules" from ${n.source}. Edit the model, not this file. -->`);
    lines.push('');
    lines.push(`# ${n.id}: ${n.role}`);
    lines.push('');
    lines.push(`These files belong to the node \`${n.id}\` (${n.kind}) in the architecture model under \`${MODEL_DIR}/\`.`);
    if (n.rules.length) {
      lines.push('');
      lines.push('## Rules');
      lines.push('');
      for (const r of n.rules) lines.push(`- ${r.text}`);
    }
    if (n.never.length) {
      lines.push('');
      lines.push('## Boundaries');
      lines.push('');
      for (const b of n.never) lines.push(`- Never import code from \`${b.node}\`, and never call, send to, read or write it${b.why ? `: ${b.why}` : '.'} \`armature check\` fails when this is broken.`);
    }
    if (n.interfaces.length) {
      lines.push('');
      lines.push('## Interfaces this node exposes');
      lines.push('');
      for (const i of n.interfaces) {
        const takes = i.takes.length ? `, takes ${i.takes.join(', ')}` : '';
        const gives = i.gives.length ? `, gives ${i.gives.join(', ')}` : '';
        lines.push(`- \`${i.ref}\`${i.via ? ` via ${i.via}` : ''}${takes}${gives}`);
      }
    }
    if (n.requirements.length) {
      lines.push('');
      lines.push('## Requirements that must keep holding');
      lines.push('');
      for (const q of n.requirements) lines.push(`- ${q.text} (tag tests with \`[req ${q.ref}]\`)`);
    }
    lines.push('');
    lines.push('## When you change these files');
    lines.push('');
    lines.push(`- Run \`armature show ${n.id}\` for the full picture, or \`armature impact ${n.id}\` before changing an interface or a shape.`);
    lines.push(`- If you add, remove or change an interface, a link to another node, or a data shape, update \`${n.source}\` (and \`${MODEL_DIR}/shapes/\`) in the same change, then run \`armature check\`.`);
    wanted.set(`${RULE_PREFIX}${n.id.replace(/\./g, '--')}.md`, `${lines.join('\n')}\n`);
  }
  let written = 0;
  let removed = 0;
  for (const [name, body] of wanted) {
    const p = path.join(dir, name);
    if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== body) {
      stale.push(`.claude/rules/${name}`);
      if (!opts.dryRun) fs.writeFileSync(p, body);
      written++;
    }
  }
  for (const f of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
    if (f.startsWith(RULE_PREFIX) && f.endsWith('.md') && !wanted.has(f)) {
      const body = fs.readFileSync(path.join(dir, f), 'utf8');
      if (GENERATED_RULE.test(body)) {
        stale.push(`.claude/rules/${f}`);
        if (!opts.dryRun) fs.unlinkSync(path.join(dir, f));
        removed++;
      }
    }
  }
  return { written, removed, stale };
}

/** True the first time `key` is seen under `name`; remembered in armature/.cache so a hook speaks once per session. */
function once(root: string, name: string, key: string): boolean {
  if (!key) return true;
  const cache = path.join(root, MODEL_DIR, '.cache');
  const marker = path.join(cache, name);
  let seen: string[] = [];
  try {
    seen = fs.readFileSync(marker, 'utf8').split('\n').filter(Boolean);
  } catch {
    /* first time */
  }
  if (seen.includes(key)) return false;
  fs.mkdirSync(cache, { recursive: true });
  fs.writeFileSync(marker, [...seen.slice(-50), key].join('\n'));
  return true;
}

/** Forgets that a session was told something, so it is told again (after the context was compacted). */
function forget(root: string, names: string[], key: string): void {
  for (const name of names) {
    const marker = path.join(root, MODEL_DIR, '.cache', name);
    try {
      fs.writeFileSync(marker, fs.readFileSync(marker, 'utf8').split('\n').filter((x) => x && x !== key).join('\n'));
    } catch {
      /* nothing remembered */
    }
  }
}

/** The permission mode a session had at its last prompt, and records the one it has now. */
function lastMode(root: string, sid: string, now: string): string | undefined {
  const marker = path.join(root, MODEL_DIR, '.cache', 'session-modes.json');
  let modes: Record<string, string> = {};
  try {
    modes = JSON.parse(fs.readFileSync(marker, 'utf8'));
  } catch {
    /* first prompt */
  }
  const was = modes[sid];
  modes[sid] = now;
  const keep = Object.fromEntries(Object.entries(modes).slice(-50));
  fs.mkdirSync(path.dirname(marker), { recursive: true });
  fs.writeFileSync(marker, JSON.stringify(keep));
  return was;
}

/** Answers a PreToolUse hook: "deny" sends the reason back to the agent, "ask" puts it in front of the person. */
function decide(decision: 'deny' | 'ask', reason: string): void {
  process.stdout.write(`${JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: decision, permissionDecisionReason: reason } })}\n`);
}

export async function hook(name: string, rootFlag?: string): Promise<void> {
  const input = parseJson(await readStdin());
  const start = rootFlag ?? input.cwd ?? process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
  const root = findRoot(start);
  if (!root) return; // no model in this project: stay silent
  try {
    if (name === 'session-start') {
      await buildCodeIndex(root).catch(() => undefined);
      const out = [orient(compile(root))];
      // Compaction drops what the session was told: tell it again, and let the next prompt bring the notes back.
      if (input.source === 'compact' || input.source === 'clear') {
        const sid = String(input.session_id ?? '');
        forget(root, ['prompted-sessions', 'plan-sessions', 'planning-sessions'], sid);
        if (gateOn(root)) out.push(`The conversation was compacted. ${planReminder(MODEL_DIR)}`);
      }
      process.stdout.write(`${out.join('\n\n')}\n`);
      return;
    }
    if (name === 'prompt') {
      const prompt: string = String(input.prompt ?? '').trim();
      if (prompt.length < 12 || prompt.startsWith('/')) return;
      const sid = String(input.session_id ?? '');
      const out: string[] = [];
      // On the first prompt of a session, add the context pack for that prompt.
      if (once(root, 'prompted-sessions', sid)) {
        await buildCodeIndex(root).catch(() => undefined);
        const idx = readCodeIndex(root);
        if (idx) out.push(contextText(compile(root), idx, root, prompt, { budget: 5000 }));
      }
      // Planning goes through the model: say so when plan mode starts, or when the prompt asks for a plan.
      // The full note comes once per session; each later plan (plan mode entered again, or a prompt asking for one) gets one line.
      const mode = String(input.permission_mode ?? 'default');
      const was = lastMode(root, sid, mode);
      if (gateOn(root)) {
        if (mode === 'plan') {
          if (once(root, 'plan-sessions', sid)) out.push(planModeNote(MODEL_DIR, newPlanPath(docsDir(root), MODEL_DIR)));
          else if (was !== 'plan') out.push(planReminder(MODEL_DIR));
        } else if (PLANNING_WORDS.test(prompt)) {
          if (once(root, 'planning-sessions', sid)) out.push(planningNote(MODEL_DIR, newPlanPath(docsDir(root), MODEL_DIR)));
          else out.push(planReminder(MODEL_DIR));
        }
      }
      if (out.length) process.stdout.write(`${out.join('\n\n')}\n`);
      return;
    }
    if (name === 'pre-write') {
      // Before a Write or Edit: new source files need a node, planned nodes need an approved change,
      // and approving a change asks the person.
      const verdict = writeGate(root, input.tool_input ?? {});
      // One question is open at a time: any other write means the earlier one was answered, so a
      // question the person declined cannot be settled by something that happens later.
      dropPendingApproval(root);
      if (!verdict) return;
      if (verdict.approves) {
        // The person sees what the change does to security before saying yes, and is not asked while it has security errors.
        const sec = changeSecurity(compile(root), verdict.approves);
        if (sec.errors.length) {
          decide('deny', `Change "${verdict.approves}" cannot be put up for approval while it has security errors. Fix them in the model first:\n${sec.errors.map((e) => `- ${e.code}: ${e.message}`).join('\n')}`);
          return;
        }
        // Kept short: the permission prompt is a small window and cuts the rest off.
        const more = sec.lines.length - 5;
        verdict.reason += `\n${sec.lines.length ? `Security:\n${sec.lines.slice(0, 5).join('\n')}${more > 0 ? `\n  and ${more} more: "armature approve" prints all` : ''}` : 'Security: no new entry point, no sensitive data sent out, no secret.'}`;
        // If the person says yes, this edit goes through and the approval is recorded after it.
        notePendingApproval(root, verdict.approves, callKey(input.tool_input));
      }
      decide(verdict.decision, verdict.reason);
      return;
    }
    if (name === 'pre-bash') {
      // Before a shell command: the same rules, for what the command plainly does.
      const verdict = bashGate(root, String(input.tool_input?.command ?? ''), typeof input.cwd === 'string' ? input.cwd : root);
      if (verdict) decide(verdict.decision, verdict.reason);
      return;
    }
    if (name === 'pre-plan') {
      // Before a plan is presented: it must say how the work changes the model.
      if (!gateOn(root)) return;
      let plan: string = typeof input.tool_input?.plan === 'string' ? input.tool_input.plan : '';
      const planFile = input.tool_input?.planFilePath;
      if (!plan && typeof planFile === 'string') {
        try {
          plan = fs.readFileSync(planFile, 'utf8');
        } catch {
          plan = '';
        }
      }
      const missing = planGate(plan, MODEL_DIR, newPlanPath(docsDir(root), MODEL_DIR), root);
      if (missing) decide('deny', missing);
      return;
    }
    if (name === 'post-edit') {
      const file: string = targetOf(input.tool_input) ?? '';
      if (!file) return;
      const rel = path.relative(root, path.resolve(root, file)).replace(/\\/g, '/');
      if (rel.startsWith('..') || rel.startsWith(`${MODEL_DIR}/.cache/`)) return;
      const inArch = rel.startsWith(`${MODEL_DIR}/`);
      const isDoc = isDocPath(rel);
      if (!inArch && !isDoc) return;
      // An approval the person has just confirmed is recorded with what the change holds now.
      // Only the edit they were asked about does this; what is added afterwards is not part of it.
      if (inArch) settleApproval(root, callKey(input.tool_input));
      const g = compile(root);
      const say: string[] = [];
      if (inArch) {
        const errors = g.problems.filter((p) => p.level === 'error');
        if (errors.length === 0) syncRules(root);
        else say.push(`armature check found problems in the architecture model after your edit to ${rel}. Fix them before continuing:\n${formatProblems(errors)}`);
      }
      if (isDoc) {
        // A document is part of the model: its references must resolve, and it should be tied to something.
        const mine = g.problems.filter((p) => p.file === rel && ['doc-reference', 'doc-header', 'typed-status'].includes(p.code));
        if (mine.length) say.push(`The document ${rel} does not match the architecture model:\n${mine.map((p) => `- ${p.message}`).join('\n')}\nUse names from the model ("armature show <ref>" confirms one), or fix the header.`);
        const doc = g.docs.find((d) => d.path === rel);
        if (doc?.loose && once(root, 'loose-docs', `${input.session_id ?? ''}|${rel}`)) {
          const hint = doc.links.slice(0, 3).map((l) => l.node).join(', ');
          say.push(
            `${rel} is not tied to the architecture model. Give it a header so people and agents find it from the parts it describes:\n---\nkind: plan | decision | guide | runbook | review | research | note\nabout: [${hint || 'node.id, node#interface, ShapeName'}]\n---\n` +
              `Name parts of the model in the text as [[node.id]], [[node#interface]] or [[ShapeName]]. New documents belong under ${docsDir(root)}/. The armature-docs skill has the format.`,
          );
        }
      }
      if (say.length) {
        process.stderr.write(`${say.join('\n\n')}\n`);
        process.exit(2);
      }
      return;
    }
    if (name === 'stop') {
      dropPendingApproval(root);
      if (input.stop_hook_active) return;
      const changed = changedFiles(root);
      if (changed.length === 0) return;
      if (changed.some((f) => f.startsWith(`${MODEL_DIR}/`) && !f.startsWith(`${MODEL_DIR}/.cache/`))) return;
      const g = compile(root);
      const touched = new Map<string, string[]>();
      for (const f of changed) {
        const n = ownerOf(g, f);
        if (!n || n.code.length === 0) continue;
        touched.set(n.id, [...(touched.get(n.id) ?? []), f]);
      }
      if (touched.size === 0) return;
      const key = createHash('sha256').update(`${input.session_id ?? ''}|${[...touched.keys()].sort().join(',')}`).digest('hex').slice(0, 16);
      const cache = path.join(root, MODEL_DIR, '.cache');
      const marker = path.join(cache, 'stop-reminder');
      let seen = '';
      try {
        seen = fs.readFileSync(marker, 'utf8');
      } catch {
        /* first time */
      }
      if (seen === key) return;
      fs.mkdirSync(cache, { recursive: true });
      fs.writeFileSync(marker, key);
      const lines = [...touched].map(([id, files]) => `- ${id}: ${files.slice(0, 4).join(', ')}${files.length > 4 ? `, and ${files.length - 4} more` : ''}`);
      const about = new Set<string>();
      for (const id of touched.keys()) for (const d of g.nodes.find((n) => n.id === id)?.docs.filter((x) => x.how === 'declared').slice(0, 2) ?? []) about.add(d.path);
      const docLine = about.size ? `Documents about them: ${[...about].slice(0, 6).join(', ')}. If what they say is no longer true, update them in the same change.\n` : '';
      process.stderr.write(
        `Code changed under these architecture nodes, and nothing under ${MODEL_DIR}/ changed:\n${lines.join('\n')}\n` +
          `Check whether an interface, a link to another node, a data shape or a requirement changed. If so, update the model under ${MODEL_DIR}/ and run "armature check". If the model still holds, say so in one line and finish.\n${docLine}`,
      );
      process.exit(2);
    }
  } catch (e: any) {
    // A broken model must never block the session.
    process.stderr.write(`armature hook ${name}: ${String(e?.message ?? e)}\n`);
  }
}

function mergeHooks(settingsPath: string): boolean {
  let settings: any = {};
  if (fs.existsSync(settingsPath)) settings = parseJson(fs.readFileSync(settingsPath, 'utf8'));
  settings.hooks ??= {};
  const cmd = (name: string): string => `node "${BIN}" hook ${name}`;
  const want: Array<[string, string | undefined, string]> = [
    ['SessionStart', undefined, cmd('session-start')],
    ['UserPromptSubmit', undefined, cmd('prompt')],
    ['PreToolUse', WRITE_TOOLS, cmd('pre-write')],
    ['PreToolUse', 'Bash', cmd('pre-bash')],
    ['PreToolUse', 'ExitPlanMode', cmd('pre-plan')],
    ['PostToolUse', WRITE_TOOLS, cmd('post-edit')],
    ['Stop', undefined, cmd('stop')],
  ];
  let changed = false;
  for (const [event, matcherText, command] of want) {
    const list: any[] = (settings.hooks[event] ??= []);
    // Drop earlier entries of ours so a moved install path does not leave duplicates. An event may
    // carry several of our hooks (two on PreToolUse), so every command wanted for it is kept.
    const wanted = new Set(want.filter((w) => w[0] === event).map((w) => w[2]));
    for (const entry of list) {
      const before = (entry.hooks ?? []).length;
      entry.hooks = (entry.hooks ?? []).filter((h: any) => !(typeof h.command === 'string' && OUR_HOOK.test(h.command) && !wanted.has(h.command)));
      if (entry.hooks.length !== before) changed = true;
    }
    const existing = list.find((entry) => (entry.hooks ?? []).some((h: any) => h.command === command));
    const present = !!existing;
    // An entry written by an earlier version may match fewer tools.
    if (existing && matcherText && existing.matcher !== matcherText) {
      existing.matcher = matcherText;
      changed = true;
    }
    if (!present) {
      const entry: any = { hooks: [{ type: 'command', command }] };
      if (matcherText) entry.matcher = matcherText;
      list.push(entry);
      changed = true;
    }
    settings.hooks[event] = list.filter((entry) => (entry.hooks ?? []).length > 0);
  }
  if (changed) {
    fs.mkdirSync(path.dirname(settingsPath), { recursive: true });
    fs.writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`);
  }
  return changed;
}

function copyDir(from: string, to: string): number {
  let count = 0;
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, e.name);
    const dst = path.join(to, e.name);
    if (e.isDirectory()) count += copyDir(src, dst);
    else {
      const body = fs.readFileSync(src);
      if (!fs.existsSync(dst) || !fs.readFileSync(dst).equals(body)) {
        fs.writeFileSync(dst, body);
        count++;
      }
    }
  }
  return count;
}

/** Wires Claude Code in a project. Everything it writes is local to this machine except skills and rule files. */
export function install(root: string): string[] {
  const out: string[] = [];
  const hooksChanged = mergeHooks(path.join(root, '.claude', 'settings.local.json'));
  out.push(`${hooksChanged ? 'Added' : 'Kept'} hooks in .claude/settings.local.json (session start, prompts, before writes and before a plan is presented, after edits to ${MODEL_DIR}/ and to documents, on stop).`);

  const mcpPath = path.join(root, '.mcp.json');
  // A committed .mcp.json is shared with the team: an entry naming a path on this machine would break theirs.
  const mcpTracked = !!git(root, ['ls-files', '--', '.mcp.json'])?.trim();
  if (mcpTracked) {
    out.push('Skipped .mcp.json: it is committed, and the entry would name a path on this machine. Agents run "armature" from the PATH instead (npm link in the Armature repo); the team install provides the MCP server.');
  } else {
    let mcp: any = {};
    if (fs.existsSync(mcpPath)) mcp = parseJson(fs.readFileSync(mcpPath, 'utf8'));
    mcp.mcpServers ??= {};
    const server = { type: 'stdio', command: 'node', args: [BIN, 'mcp'] };
    if (JSON.stringify(mcp.mcpServers.armature) !== JSON.stringify(server)) {
      mcp.mcpServers.armature = server;
      fs.writeFileSync(mcpPath, `${JSON.stringify(mcp, null, 2)}\n`);
      out.push('Registered the "armature" MCP server in .mcp.json.');
    } else out.push('Kept the "armature" MCP server in .mcp.json.');
  }

  const skills = copyDir(path.join(PKG_ROOT, 'skills'), path.join(root, '.claude', 'skills'));
  out.push(`Skills: ${skills} file${skills === 1 ? '' : 's'} copied to .claude/skills/.`);

  const rules = syncRules(root);
  out.push(`Rule files: ${rules.written} written, ${rules.removed} removed in .claude/rules/.`);

  const ignore = path.join(root, MODEL_DIR, '.gitignore');
  if (!fs.existsSync(ignore)) {
    fs.writeFileSync(ignore, '.cache/\n');
    out.push(`Created ${MODEL_DIR}/.gitignore so derived files stay out of git.`);
  }
  out.push(`Restart the Claude Code session in this repo so the hooks${mcpTracked ? '' : ' and MCP server'} load.`);
  return out;
}

