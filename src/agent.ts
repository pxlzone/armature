export const PLUGIN = 'armature';

export type MarketplaceSource = { source: 'github'; repo: string; ref?: string } | { source: 'git'; url: string; ref?: string } | { source: 'directory'; path: string };

function marketplaceName(): string {
  try {
    return JSON.parse(fs.readFileSync(path.join(PKG_ROOT, '.claude-plugin', 'marketplace.json'), 'utf8')).name ?? 'armature';
  } catch {
    return 'armature';
  }
}

/** Reads `owner/repo`, a git URL or a local folder. Falls back to this package's git remote. */
export function parseMarketplace(text: string | undefined, ref?: string): MarketplaceSource | null {
  let t = text?.trim();
  if (!t) {
    try {
      t = String(execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: PKG_ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })).trim();
    } catch {
      return null;
    }
  }
  if (!t) return null;
  const gh = t.match(/^(?:https:\/\/github\.com\/|git@github\.com:)?([\w.-]+\/[\w.-]+?)(?:\.git)?\/?$/);
  if (gh && !fs.existsSync(t)) return { source: 'github', repo: gh[1], ...(ref ? { ref } : {}) };
  if (/^(https?:|ssh:|git@)/.test(t) || t.endsWith('.git')) return { source: 'git', url: t, ...(ref ? { ref } : {}) };
  const abs = path.resolve(t);
  if (fs.existsSync(path.join(abs, '.claude-plugin', 'marketplace.json'))) return { source: 'directory', path: abs };
  return null;
}

function readJson(p: string): any {
  return fs.existsSync(p) ? parseJson(fs.readFileSync(p, 'utf8')) : {};
}

function writeJson(p: string, value: any): void {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, `${JSON.stringify(value, null, 2)}\n`);
}

/** Removes what a local `armature install` wrote, so the plugin does not run everything twice. */
function removeLocalWiring(root: string): string[] {
  const out: string[] = [];
  const local = path.join(root, '.claude', 'settings.local.json');
  if (fs.existsSync(local)) {
    const s = readJson(local);
    let dropped = 0;
    for (const [event, list] of Object.entries<any[]>(s.hooks ?? {})) {
      for (const entry of list) {
        const before = (entry.hooks ?? []).length;
        entry.hooks = (entry.hooks ?? []).filter((h: any) => !(typeof h.command === 'string' && OUR_HOOK.test(h.command)));
        dropped += before - entry.hooks.length;
      }
      s.hooks[event] = list.filter((e) => (e.hooks ?? []).length > 0);
      if (s.hooks[event].length === 0) delete s.hooks[event];
    }
    if (s.hooks && Object.keys(s.hooks).length === 0) delete s.hooks;
    if (dropped) {
      writeJson(local, s);
      out.push(`Removed ${dropped} local armature hook${dropped === 1 ? '' : 's'} from .claude/settings.local.json (the plugin runs them now).`);
    }
  }
  const mcpPath = path.join(root, '.mcp.json');
  const mcp = readJson(mcpPath);
  if ((mcp.mcpServers?.armature?.args ?? []).some((a: string) => /armature\.mjs$/.test(a) && path.isAbsolute(a))) {
    delete mcp.mcpServers.armature;
    if (Object.keys(mcp.mcpServers).length === 0 && Object.keys(mcp).length === 1) fs.unlinkSync(mcpPath);
    else writeJson(mcpPath, mcp);
    out.push('Removed the machine-specific "armature" server from .mcp.json (the plugin provides it).');
  }
  // Skills copied by a local install, untouched since: the plugin ships them, namespaced as armature:<skill>.
  const src = path.join(PKG_ROOT, 'skills');
  for (const name of fs.existsSync(src) ? fs.readdirSync(src) : []) {
    const copy = path.join(root, '.claude', 'skills', name, 'SKILL.md');
    const ours = path.join(src, name, 'SKILL.md');
    if (fs.existsSync(copy) && fs.existsSync(ours) && fs.readFileSync(copy, 'utf8') === fs.readFileSync(ours, 'utf8')) {
      fs.rmSync(path.dirname(copy), { recursive: true, force: true });
      out.push(`Removed the copied skill .claude/skills/${name}/ (the plugin ships it).`);
    }
  }
  const skillsDir = path.join(root, '.claude', 'skills');
  if (fs.existsSync(skillsDir) && fs.readdirSync(skillsDir).length === 0) fs.rmdirSync(skillsDir);
  return out;
}

/** The GitHub Actions job: model check with annotations, rule files up to date, and the diagram as an artifact. */
export function ciWorkflow(source: MarketplaceSource): string | null {
  let fetch: string;
  if (source.source === 'github') {
    fetch = [
      '      - name: Get armature',
      '        uses: actions/checkout@v4',
      '        with:',
      `          repository: ${source.repo}`,
      ...(source.ref ? [`          ref: ${source.ref}`] : []),
      '          path: .armature',
      '          # If the tool repo is private, add a read-only token as the ARMATURE_REPO_TOKEN secret.',
      '          token: ${{ secrets.ARMATURE_REPO_TOKEN || github.token }}',
    ].join('\n');
  } else if (source.source === 'git') {
    fetch = ['      - name: Get armature', `        run: git clone --depth 1 ${source.ref ? `--branch ${source.ref} ` : ''}${source.url} .armature`].join('\n');
  } else return null;
  return `# Generated by "armature install --team". Keeps the architecture model in armature/ true to the code.
name: architecture

on:
  pull_request:
    paths-ignore: ['**/*.md']
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  model:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0 # history feeds activity and co-change
${fetch}
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      # Requirements count as verified only with a test report newer than the code. This job runs
      # no tests, so a finished change is reported as "cannot be checked here", never failed for it.
      # To have CI check requirements, run your tests with a JUnit reporter into
      # armature/.cache/reports/ before the next step.
      - name: Check the model
        # Errors fail the job. Warnings where the model is wrong show as warnings on the pull
        # request; warnings where it is only incomplete show as notices.
        # While the team adopts the model, uncomment the next line to report without blocking.
        # continue-on-error: true
        # On a pull request only what it adds is shown: the same check runs on the base branch and
        # warnings that were already there are left out. A new warning where the model is wrong
        # (code the model does not declare, a finished change with no test) fails the job;
        # remove "--fail-on wrong" to report without failing.
        run: |
          if [ "\${{ github.event_name }}" = "pull_request" ]; then
            node .armature/plugin/bin/armature.mjs check --annotate --since "origin/\${{ github.base_ref }}" --fail-on wrong
          else
            node .armature/plugin/bin/armature.mjs check --annotate
          fi
      - name: Rule files match the model
        run: node .armature/plugin/bin/armature.mjs sync-rules --check
      - name: What this pull request changes in the model
        if: github.event_name == 'pull_request'
        run: node .armature/plugin/bin/armature.mjs diff "origin/\${{ github.base_ref }}" >> "$GITHUB_STEP_SUMMARY"
      - name: Diagram
        if: always()
        run: node .armature/plugin/bin/armature.mjs export architecture.html
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: architecture
          path: architecture.html
`;
}

export interface TeamOptions {
  marketplace?: string;
  ref?: string;
  ci?: boolean;
}

/** Wires a repo for the whole team. Everything it writes is meant to be committed. */
export function installTeam(root: string, opts: TeamOptions = {}): string[] {
  const source = parseMarketplace(opts.marketplace, opts.ref);
  if (!source) {
    throw new Error(
      'Where do teammates get the plugin from? Pass --marketplace with the armature repo: owner/repo on GitHub, a git URL, or a local folder (that one works only on this machine).',
    );
  }
  const out: string[] = [];
  const market = marketplaceName();
  const id = `${PLUGIN}@${market}`;

  const settingsPath = path.join(root, '.claude', 'settings.json');
  const settings = readJson(settingsPath);
  const before = JSON.stringify(settings);
  settings.extraKnownMarketplaces ??= {};
  settings.extraKnownMarketplaces[market] = { source };
  settings.enabledPlugins ??= {};
  settings.enabledPlugins[id] = true;
  if (JSON.stringify(settings) !== before) {
    writeJson(settingsPath, settings);
    out.push(`Enabled the plugin ${id} for everyone in .claude/settings.json.`);
  } else out.push(`Kept the plugin ${id} in .claude/settings.json.`);
  if (source.source === 'directory') out.push(`Note: the marketplace is a folder on this machine (${source.path}). Teammates need --marketplace owner/repo or a git URL instead.`);

  out.push(...removeLocalWiring(root));

  const rules = syncRules(root);
  out.push(`Rule files: ${rules.written} written, ${rules.removed} removed in .claude/rules/.`);

  const ignore = path.join(root, MODEL_DIR, '.gitignore');
  if (!fs.existsSync(ignore)) {
    fs.writeFileSync(ignore, '.cache/\n');
    out.push(`Created ${MODEL_DIR}/.gitignore so derived files stay out of git.`);
  }

  if (opts.ci !== false) {
    const wf = ciWorkflow(source);
    const wfPath = path.join(root, '.github', 'workflows', 'architecture.yml');
    if (!wf) out.push('Skipped the CI workflow: CI cannot reach a marketplace in a local folder.');
    else if (fs.existsSync(wfPath) && fs.readFileSync(wfPath, 'utf8') !== wf && !/^# Generated by "armature install --team"/.test(fs.readFileSync(wfPath, 'utf8'))) {
      out.push('Kept .github/workflows/architecture.yml: it was edited by hand.');
    } else if (!fs.existsSync(wfPath) || fs.readFileSync(wfPath, 'utf8') !== wf) {
      fs.mkdirSync(path.dirname(wfPath), { recursive: true });
      fs.writeFileSync(wfPath, wf);
      out.push('Wrote .github/workflows/architecture.yml (model check, rule files, diagram artifact).');
    }
  }

  out.push('');
  out.push(`Commit: ${MODEL_DIR}/, .claude/settings.json, .claude/rules/armature-*.md${opts.ci !== false && source.source !== 'directory' ? ', .github/workflows/architecture.yml' : ''}.`);
  out.push('Each teammate: open the repo in Claude Code, trust the folder, and run /plugin install ' + id + ' once if Claude Code has not installed it. Node 22+ is the only requirement.');
  return out;
}
